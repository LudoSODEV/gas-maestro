<template>
	<div class="card">
		<h2>Gestion des bases de données</h2>
		<p class="description">Gérez vos connexions aux feuilles de calcul Google Sheets agissant comme bases de données régionales.</p>

		<div v-if="loading" class="loading">Chargement des bases de données...</div>

		<div v-else>
			<table>
				<thead>
					<tr>
						<th>Nom de la base (dbKey)</th>
						<th>Nom de la Base</th>
						<th>Identifiant du fichier (Spreadsheet ID)</th>
						<th>Actions</th>
					</tr>
				</thead>
				<tbody>
					<tr v-for="(db, index) in dbs" :key="index">
						<td><input v-model="db.dbKey" type="text" readonly style="background: #e9ecef;" /></td>
						<td><input v-model="db.dbName" type="text" readonly style="background: #e9ecef;" /></td>
						<td><input v-model="db.spreadsheetId" type="text" style="width: 300px;" /></td>
						<td>
							<a v-if="db.spreadsheetId" :href="'https://docs.google.com/spreadsheets/d/' + db.spreadsheetId" target="_blank" class="btn-link">Ouvrir</a>
							<button class="danger" @click="removeDb(index)">Supprimer</button>
						</td>
					</tr>
					<tr v-if="dbs.length === 0">
						<td colspan="4" style="text-align: center;">Aucune base de données configurée.</td>
					</tr>
				</tbody>
			</table>

			<div class="action-bar">
				<button class="primary" @click="autoGenerateDb" style="background: #319795;">⚙️ Générer/Synchroniser ma base de données automatique</button>
				<button class="primary" @click="saveDbs" style="background: #2b6cb0;">Enregistrer les modifications</button>
			</div>

			<p v-if="statusMessage" class="status-msg" :style="{ color: statusColor }">{{ statusMessage }}</p>
		</div>
	</div>
</template>

<script lang="ts">
import { ref, onMounted } from 'vue'

interface DatabaseItem {
	dbKey: string;
	dbName?: string;
	spreadsheetId: string;
}

export default {
	name: 'DatabaseManagement',
	setup()
	{
		const dbs = ref<DatabaseItem[]>([])
		const loading = ref(true)
		const statusMessage = ref('')
		const statusColor = ref('green')

		const loadDbs = () =>
		{
			loading.value = true
			if (window.google?.script?.run)
			{
				window.google.script.run
					.withSuccessHandler((data: DatabaseItem[]) =>
					{
						dbs.value = data
						loading.value = false
					})
					.withFailureHandler((err: any) =>
					{
						statusMessage.value = 'Erreur lors du chargement: ' + err.message
						statusColor.value = 'red'
						loading.value = false
					})
					.Maestro_getUserDbs()
			}
			else
			{
				// Local dev mock
				dbs.value = [
					{ dbKey: 'ba13', dbName: 'BA13', spreadsheetId: 'mock-spreadsheet-id-13' }
				]
				loading.value = false
			}
		}

		const removeDb = (index: number) =>
		{
			dbs.value.splice(index, 1)
		}

		const saveDbs = () =>
		{
			statusMessage.value = 'Enregistrement en cours...'
			statusColor.value = 'blue'
			if (window.google?.script?.run)
			{
				window.google.script.run
					.withSuccessHandler(() =>
					{
						statusMessage.value = 'Modifications enregistrées avec succès !'
						statusColor.value = 'green'
					})
					.withFailureHandler((err: any) =>
					{
						statusMessage.value = 'Erreur lors de l\'enregistrement: ' + err.message
						statusColor.value = 'red'
					})
					.Maestro_saveUserDbs(dbs.value)
			}
			else
			{
				setTimeout(() =>
				{
					statusMessage.value = 'Modifications enregistrées avec succès ! (Mode Local)'
					statusColor.value = 'green'
				}, 500)
			}
		}

		const autoGenerateDb = () =>
		{
			statusMessage.value = 'Génération automatique de la base de données en cours...'
			statusColor.value = 'blue'

			if (window.google?.script?.run)
			{
				window.google.script.run
					.withSuccessHandler((newDb: DatabaseItem) =>
					{
						if (!dbs.value.some((d: DatabaseItem) => d.dbKey === newDb.dbKey))
						{
							dbs.value.push(newDb)
						}
						statusMessage.value = 'Base de données générée et synchronisée avec succès !'
						statusColor.value = 'green'
					})
					.withFailureHandler((err: any) =>
					{
						statusMessage.value = 'Erreur lors de la génération automatique: ' + err.message
						statusColor.value = 'red'
					})
					.Maestro_getOrCreateAutoDb()
			}
			else
			{
				setTimeout(() =>
				{
					const mockDb: DatabaseItem = { dbKey: 'ba13', dbName: 'BA13', spreadsheetId: 'mock-auto-id' }
					if (!dbs.value.some((d: DatabaseItem) => d.dbKey === mockDb.dbKey))
					{
						dbs.value.push(mockDb)
					}
					statusMessage.value = 'Base de données générée et synchronisée avec succès ! (Mode Local)'
					statusColor.value = 'green'
				}, 500)
			}
		}

		onMounted(() =>
		{
			loadDbs()
		})

		return {
			dbs,
			loading,
			statusMessage,
			statusColor,
			removeDb,
			saveDbs,
			autoGenerateDb
		}
	}
}
</script>

